/* 按出身/路线/属性 → 派发时归一权重 */
function fateGroupWeights(s){
  const r = {商:1, 文:1, 武:1, 医:1, 堂:1, 心:1, 灾:1, 奇:1};
  if(s.tags.indexOf('秀才')>=0 || s.attrs.才>=4) r.文 += 2;
  if(s.tags.indexOf('弓马')>=0 || s.tags.indexOf('行伍')>=0 || s.attrs.武>=3) r.武 += 2;
  if(s.attrs.财>=4) r.商 += 2;
  if(!!(s.routes.yi && s.routes.yi.active)) r.医 += 4;
  if(!!(s.routes.zheng && s.routes.zheng.active)) r.文 += 2;
  if(!!(s.routes.jun && s.routes.jun.active)) r.武 += 2;
  if(!!(s.routes.shang && s.routes.shang.active)) r.商 += 2;
  if(s.rank<=1){ r.堂 -= 1; r.灾 += 1; }
  if(s.mind>=7) r.心 += 2;
  if(s.flags.家族破败) r.奇 += 2;
  /* 归一：保底 1 */
  for(const k in r) if(r[k] < 1) r[k] = 1;
  return r;
}

